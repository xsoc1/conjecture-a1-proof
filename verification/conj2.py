"""
Honest computation in  M_{p,q} = A / (A X^{p+1} + A Y^{q+1}),
A = U(h_1) = K<X,Y,Z>/([X,Y]=Z, Z central),  basis X^a Y^b Z^k of A (PBW).

A is graded by deg X = deg Y = 1, deg Z = 2.  The left ideal I is generated by
homogeneous elements, hence graded:  I_d = A_{d-p-1} X^{p+1} + A_{d-q-1} Y^{q+1}.
So  M_d = A_d / I_d  and everything is finite dimensional linear algebra.

Products used (all exact):
  (X^a Y^b Z^k) * X^n = sum_{j=0}^{min(b,n)} (-1)^j C(b,j)C(n,j) j!  X^{a+n-j} Y^{b-j} Z^{k+j}
  (X^a Y^b Z^k) * Y^n = X^a Y^{b+n} Z^k
"""
from fractions import Fraction as F
from math import comb, factorial

def normal_order_times_X_pow(a, b, k, n):
    """(X^a Y^b Z^k) * X^n expanded in the PBW basis  X^? Y^? Z^?"""
    out = {}
    for j in range(0, min(b, n) + 1):
        coef = F((-1)**j * comb(b, j) * comb(n, j) * factorial(j))
        key = (a + n - j, b - j, k + j)
        out[key] = out.get(key, F(0)) + coef
    return {kk: v for kk, v in out.items() if v != 0}

def basis_degree(d):
    """PBW monomials X^a Y^b Z^k of total degree a+b+2k = d, sorted"""
    res = []
    k = 0
    while 2*k <= d:
        s = d - 2*k
        for a in range(0, s + 1):
            res.append((a, s - a, k))
        k += 1
    return sorted(res)

def I_basis(d, p, q):
    """spanning set of I_d = A_{d-p-1} X^{p+1} + A_{d-q-1} Y^{q+1}"""
    gens = []
    if d - p - 1 >= 0:
        for (a, b, k) in basis_degree(d - p - 1):
            gens.append(normal_order_times_X_pow(a, b, k, p + 1))
    if d - q - 1 >= 0:
        for (a, b, k) in basis_degree(d - q - 1):
            gens.append({(a, b + q + 1, k): F(1)})
    return gens

class Quotient:
    def __init__(self, p, q, maxdeg):
        if min(p, q, maxdeg) < 0:
            raise ValueError("p, q and maxdeg must be nonnegative")
        self.p, self.q = p, q
        self.basis = {d: basis_degree(d) for d in range(maxdeg + 1)}
        self.index = {d: {m: i for i, m in enumerate(self.basis[d])} for d in self.basis}
        # reduced row echelon data for I_d : list of (pivot_index, row as dict idx->coef)
        self.reduced = {}
        for d in self.basis:
            self.reduced[d] = self.reduce_basis(I_basis(d, p, q), d)

    def reduce_basis(self, gens, d):
        """Gaussian elimination; returns normalized forward-echelon pivot rows.

        Earlier rows need not have zero entries above later pivots. Reduction in
        ascending pivot order is sufficient for exact membership decisions.
        """
        rows = []
        for g in gens:
            rows.append(self.to_index_vector(g, d))
        pivots = []   # list of (pivot_col, row_vector_dict)
        for vec in rows:
            cur = dict(vec)
            for (pc, prow) in pivots:
                if pc in cur:
                    f = cur[pc]
                    for c, val in prow.items():
                        cur[c] = cur.get(c, F(0)) - f * val
                    cur = {c: v for c, v in cur.items() if v != 0}
            if cur:
                pc = min(cur)
                inv = F(1) / cur[pc]
                cur = {c: v * inv for c, v in cur.items()}
                pivots.append((pc, cur))
                pivots.sort(key=lambda t: t[0])
        return pivots

    def to_index_vector(self, elem, d):
        idx = self.index[d]
        if any(c != 0 and m not in idx for m, c in elem.items()):
            raise ValueError("nonzero monomial outside the requested homogeneous degree")
        return {idx[m]: F(c) for m, c in elem.items() if c != 0}

    def to_elem(self, vec, d):
        bd = self.basis[d]
        return {bd[i]: c for i, c in vec.items() if c != 0}

    def reduce(self, elem, d):
        """reduce an element of A_d modulo I_d"""
        cur = self.to_index_vector(elem, d)
        for (pc, prow) in self.reduced[d]:
            if pc in cur:
                f = cur[pc]
                for c, val in prow.items():
                    cur[c] = cur.get(c, F(0)) - f * val
                cur = {c: v for c, v in cur.items() if v != 0}
        return cur   # vector in A_d / I_d

    def mulX(self, elem):
        out = {}
        for (a, b, k), c in elem.items():
            out[(a + 1, b, k)] = out.get((a + 1, b, k), F(0)) + c
        return out

    def mulY(self, elem):
        out = {}
        for (a, b, k), c in elem.items():
            out[(a, b + 1, k)] = out.get((a, b + 1, k), F(0)) + c
            if a >= 1:
                out[(a - 1, b, k + 1)] = out.get((a - 1, b, k + 1), F(0)) - a * c
        return {kk: v for kk, v in out.items() if v != 0}

    def step_T(self, elem, d_new):
        img = {}
        for (a, b, k), c in elem.items():
            img[(a + 1, b, k)] = img.get((a + 1, b, k), F(0)) + c
            img[(a, b + 1, k)] = img.get((a, b + 1, k), F(0)) + c
            if a >= 1:
                img[(a - 1, b, k + 1)] = img.get((a - 1, b, k + 1), F(0)) - a * c
        img = {kk: v for kk, v in img.items() if v != 0}
        return self.to_elem(self.reduce(img, d_new), d_new)

def T_powers(p, q, nmax):
    """returns list v_0,...,v_nmax with v_n = (X+Y)^n . 1  in M_{p,q}"""
    Q = Quotient(p, q, nmax)
    vs = []
    cur = {(0, 0, 0): F(1)}     # 1 in A_0 ; I_0 = 0
    vs.append(cur)
    for n in range(1, nmax + 1):
        cur = Q.step_T(cur, n)
        vs.append(cur)
    return vs

